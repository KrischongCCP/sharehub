def frame(img, x, y, radius):
    mask=Image.new('L',img.size,0)
    ImageDraw.Draw(mask).rounded_rectangle((0,0,img.width-1,img.height-1),radius=radius,fill=255)
    shadow=Image.new('RGBA',board.size,(0,0,0,0))
    ImageDraw.Draw(shadow).rounded_rectangle((x+1,y+7,x+img.width+1,y+img.height+7),radius=radius,fill=(30,61,43,28))
    shadow=shadow.filter(ImageFilter.GaussianBlur(12))
    board.paste(shadow,(0,0),shadow)
    board.paste(img,(x,y),mask)
    ImageDraw.Draw(board).rounded_rectangle((x,y,x+img.width-1,y+img.height-1),radius=radius,outline='#d1dcd0',width=1)
